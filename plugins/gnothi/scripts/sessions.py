from __future__ import annotations

import hashlib
import re
from dataclasses import asdict, dataclass, field
from datetime import date, datetime, timedelta
from typing import List, Optional

KINDS = ("edit", "read", "shell", "test", "skill", "mcp", "subagent", "plan", "other")
PERIODS = {"all": None, "year": 365, "half": 182, "month": 30}
PREFIX = {"claude": "cc", "codex": "cx", "cursor": "cu"}
CACHE_VERSION = 2

INJECTED = re.compile(r"<(system-reminder|environment_context|INSTRUCTIONS|user_instructions|local-command-stdout|"
                      r"local-command-stderr|command-message|command-args|timestamp|attached_files|"
                      r"system_notification|subagent_notification|artifact-view-context|manually_attached_skills|task-notification|"
                      r"send_user_message_question_reply|bash-input|bash-stdout|bash-stderr|user-memory-input|turn_aborted|"
                      r"user_shell_command|skill)\b[^>]*>.*?</\1>", re.S)
AGENTS = re.compile(r"^# AGENTS\.md instructions.*?(?=\n\n(?!<)|\Z)", re.S)
COMMAND = re.compile(r"<command-name>\s*(.*?)\s*</command-name>", re.S)
SKILL_FILE = re.compile(r"skills/([\w.-]+)/SKILL\.md")
PASTED = re.compile(r"<pasted_content\b[^>]*>.*?</pasted_content[^>]*>", re.S)
CURSOR_COMMAND = re.compile(r"<cursor_commands>.*?Cursor Command:\s*([\w.:-]+).*?</cursor_commands>", re.S)
QUERY = re.compile(r"</?user_query>")
AUTOMATIC = re.compile(r"^(\[Request interrupted by user[^\]]*\]|Briefly inform the user about the task result\b.*|"
                       r"Caveat: The messages below were generated by the user while running local commands\b.*|"
                       r"The following is the Codex agent history\b.*|The beginning of the above subagent result\b.*|"
                       r"Perform any necessary follow-up actions\b.*)$", re.S)
TEST = re.compile(r"\b(pytest|unittest|phpunit|jest|vitest|go test|cargo test|npm (run )?test|ruff|eslint|phpcs|"
                  r"phpstan|mypy|tsc|lint|build)\b")
TOOLS = {
    "edit": {"Edit", "Write", "MultiEdit", "NotebookEdit", "apply_patch", "edit_file", "search_replace", "write"},
    "read": {"Read", "Grep", "Glob", "LS", "read_file", "grep", "codebase_search", "list_dir", "file_search"},
    "shell": {"Bash", "Shell", "exec_command", "exec", "shell", "run_terminal_cmd", "local_shell"},
    "subagent": {"Task", "Agent", "spawn_agent"},
    "plan": {"EnterPlanMode", "ExitPlanMode", "update_plan", "TodoWrite"},
    "mcp": {"CallDynamicTool"},
}


@dataclass
class Action:
    tool: str
    kind: str
    name: str = ""


@dataclass
class Turn:
    ts: Optional[datetime]
    request: str
    actions: List[Action] = field(default_factory=list)
    outcome: str = "unknown"
    tokens: Optional[int] = None


@dataclass
class Session:
    client: str
    id: str
    project: str
    path: str
    started: Optional[datetime]
    ended: Optional[datetime]
    turns: List[Turn] = field(default_factory=list)
    compactions: int = 0
    skipped: int = 0


def session_id(client, path):
    return f"{PREFIX[client]}-{hashlib.sha1(str(path).encode('utf-8')).hexdigest()[:8]}"


def clean_request(text):
    text = COMMAND.sub(lambda match: match.group(1), str(text or ""))
    text = CURSOR_COMMAND.sub(lambda match: "/" + match.group(1), text)
    text = PASTED.sub("[pasted text]", text)
    text = INJECTED.sub("", text)
    text = AGENTS.sub("", text.strip())
    text = QUERY.sub("", text).strip()
    return "" if AUTOMATIC.match(text) else text


def classify(tool, detail=""):
    detail = str(detail or "")

    if tool == "Skill":
        return Action(tool, "skill", detail)

    if tool.startswith("mcp__"):
        return Action(tool, "mcp", tool.split("__")[1])

    skill = SKILL_FILE.search(detail)

    if skill and tool not in TOOLS["edit"]:
        return Action(tool, "skill", skill.group(1))

    for kind, names in TOOLS.items():
        if tool in names:
            if kind == "shell" and TEST.search(detail):
                return Action(tool, "test")

            return Action(tool, kind)

    return Action(tool, "other")


def window(period, today):
    if period not in PERIODS:
        raise ValueError(f"Unknown period {period}; use one of {', '.join(PERIODS)}")
    days = PERIODS[period]

    if not days:
        return {"start": None, "end": today, "previous": None}

    start = today - timedelta(days=days - 1)
    previous_end = start - timedelta(days=1)
    return {"start": start, "end": today,
            "previous": {"start": previous_end - timedelta(days=days - 1), "end": previous_end}}


def moment(value):
    return datetime.fromisoformat(value) if value else None


def session_to_json(session):
    data = asdict(session)
    data["started"] = session.started.isoformat() if session.started else None
    data["ended"] = session.ended.isoformat() if session.ended else None

    for turn, source in zip(data["turns"], session.turns):
        turn["ts"] = source.ts.isoformat() if source.ts else None

    return data


def session_from_json(data):
    turns = [Turn(moment(turn["ts"]), turn["request"], [Action(**action) for action in turn["actions"]],
                  turn["outcome"], turn["tokens"]) for turn in data["turns"]]
    return Session(data["client"], data["id"], data["project"], data["path"], moment(data["started"]),
                   moment(data["ended"]), turns, data.get("compactions", 0), data.get("skipped", 0))


def cache_file(adapter, path):
    import storage

    return storage.data_root() / "cache" / adapter.CLIENT / f"{hashlib.sha1(str(path).encode('utf-8')).hexdigest()[:16]}.json"


def prune(adapter, paths):
    keep = {cache_file(adapter, path).name for path in paths}

    for stale in cache_file(adapter, "").parent.glob("*.json"):
        if stale.name not in keep:
            try:
                stale.unlink()
            except OSError:
                pass


def cached(adapter, path):
    import json

    import storage

    info = path.stat()
    key = [CACHE_VERSION, info.st_size, info.st_mtime_ns]
    target = cache_file(adapter, path)

    try:
        data = json.loads(target.read_text(encoding="utf-8"))

        if data.get("key") == key:
            return session_from_json(data["session"])
    except (OSError, ValueError, KeyError, TypeError):
        pass

    session = adapter.read(path)
    storage.write_private(target, json.dumps({"key": key, "session": session_to_json(session)}, ensure_ascii=False))
    return session


def load(start, end):
    from sources import ADAPTERS

    found, stats = [], []

    for adapter in ADAPTERS:
        base = adapter.root()
        paths = list(adapter.files(base))
        entry = {"client": adapter.CLIENT, "root": str(base), "found": bool(paths), "files": len(paths),
                 "sessions": 0, "skipped_lines": 0, "failed_files": 0}

        for path in paths:
            try:
                session = cached(adapter, path)
            except Exception:
                entry["failed_files"] += 1
                continue

            entry["skipped_lines"] += session.skipped

            if not session.turns or not session.started:
                continue

            day = session.started.astimezone().date()

            if (start is None or day >= start) and day <= end:
                found.append(session)
                entry["sessions"] += 1

        prune(adapter, paths)
        stats.append(entry)

    return found, stats
